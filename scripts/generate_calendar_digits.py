#!/usr/bin/env python3
"""Generate the oversized calendar day glyphs used by the tear-off calendar sleep screen.

The sleep screen shows the solar day as a large number (the signature element of a
Vietnamese "lịch bloc"). The built-in UI fonts top out at 16pt, so the digits are
rasterised once from Bitter-Bold (already vendored for the built-in font set) and
embedded as a 1-bit bitmap: 1 = white, 0 = black, MSB first, which is exactly what
`GfxRenderer::drawImage` / `FreeInkDisplay::blitImage` expect.

Glyph cells are padded to a multiple of 8 pixels wide so every row starts on a byte
boundary, and every digit is bottom-aligned inside its cell so two digits sharing a
baseline line up like a printed calendar page.

Usage:
    python3 scripts/generate_calendar_digits.py [--height 160] [--width 200]
"""

from __future__ import annotations

import argparse
import pathlib
import sys

try:
    from PIL import Image, ImageDraw, ImageFont
except ImportError:  # pragma: no cover - developer tooling only
    sys.stderr.write("Pillow is required: python3 -m pip install Pillow\n")
    raise SystemExit(1) from None


REPO_ROOT = pathlib.Path(__file__).resolve().parent.parent
FONT_PATH = REPO_ROOT / "lib" / "EpdFont" / "builtinFonts" / "source" / "Bitter" / "Bitter-Bold.ttf"
OUTPUT_PATH = REPO_ROOT / "src" / "images" / "CalendarDigits.h"

# Supersampling factor for the rasterised glyph; the shape is downsampled with a
# coverage threshold so the final 1-bit edges stay smooth on the panel.
SUPERSAMPLE = 4
INK_THRESHOLD = 128
INK_PAD = 6  # transparent margin kept around each glyph inside its own cell


def render_digit_alpha(digit: str, height: int, font: ImageFont.FreeTypeFont) -> Image.Image:
    """Render one digit to an 8-bit alpha mask, cropped to its ink box."""
    font_size = round(font.size)
    canvas = Image.new("L", (font_size * 4, font_size * 4), 0)
    draw = ImageDraw.Draw(canvas)
    draw.text((font_size, font_size), digit, fill=255, font=font)
    bbox = canvas.getbbox()
    if bbox is None:
        raise RuntimeError(f"digit {digit!r} produced no ink")
    glyph = canvas.crop(bbox)

    # Scale so the ink is exactly `height` tall, preserving the aspect ratio.
    scale = height / glyph.height
    target = (max(1, round(glyph.width * scale)), height)
    return glyph.resize(target, Image.Resampling.LANCZOS)


def pack_row_major(mask: Image.Image, width: int, height: int) -> bytearray:
    """Pack a 1-bit mask as MSB-first rows, 1 = white, 0 = black.

    The panel convention is 1 = white and 0 = black, so each cell starts fully
    white and every ink pixel clears its bit.
    """
    ink = mask.point(lambda value: 0 if value >= INK_THRESHOLD else 255).tobytes()
    stride = width // 8
    data = bytearray(b"\xff" * (stride * height))
    for y in range(height):
        row_offset = y * width
        for x in range(width):
            if ink[row_offset + x] == 0:
                data[y * stride + (x >> 3)] &= ~(0x80 >> (x & 7))
    return data


def build(height: int, min_width: int) -> tuple[list[bytearray], list[int], int]:
    font_size = height * SUPERSAMPLE
    font = ImageFont.truetype(str(FONT_PATH), font_size)

    glyphs = [render_digit_alpha(str(d), height, font) for d in range(10)]

    # Each digit gets a cell only as wide as its own ink plus a small uniform
    # margin, rounded up to a whole byte. A fixed-width cell would leave a hole
    # beside narrow glyphs like '1' and make two-digit days look off-centre.
    cells: list[Image.Image] = []
    for glyph in glyphs:
        cell_width = ((glyph.width + 2 * INK_PAD + 7) // 8) * 8
        cell_width = max(cell_width, ((min_width + 7) // 8) * 8)
        cell = Image.new("L", (cell_width, height), 0)
        cell.paste(glyph, ((cell_width - glyph.width) // 2, height - glyph.height))
        cells.append(cell)

    widths = [cell.width for cell in cells]
    # Each digit keeps its own width, so its own row stride. The drawing side
    # must pass exactly that width, otherwise rows shear into stripes.
    packed = [pack_row_major(cell, cell.width, height) for cell in cells]
    return packed, widths, height


def emit(packed: list[bytearray], widths: list[int], height: int) -> str:
    lines = [
        "#pragma once",
        "#include <cstdint>",
        "",
        "// Generated by scripts/generate_calendar_digits.py -- do not edit by hand.",
        "// '0'-'9' as oversized day glyphs for the tear-off calendar sleep screen.",
        f"// {height}px tall, 1bpp, MSB first, 1 = white, 0 = black.",
        "// One array per digit so each keeps its own row stride; pass the matching",
        "// CalendarDigitWidths entry as the image width.",
        "static constexpr int CalendarDigitHeight = " + str(height) + ";",
        "static constexpr int CalendarDigitWidths[10] = {" + ", ".join(str(w) for w in widths) + "};",
    ]
    for digit, (data, width) in enumerate(zip(packed, widths, strict=True)):
        stride = width // 8
        lines.append("")
        lines.append(f"static const uint8_t CalendarDigit{digit}[] = {{")
        for offset in range(0, len(data), stride):
            row = data[offset : offset + stride]
            lines.append("    " + " ".join(f"0x{byte:02x}," for byte in row))
        lines.append("};")
    lines.append("")
    lines.append("// Indexed by digit value.")
    lines.append(
        "static const uint8_t* const CalendarDigits[10] = {"
        + ", ".join(f"CalendarDigit{digit}" for digit in range(10))
        + "};"
    )
    lines.append("")
    return "\n".join(lines)
    for digit, data in enumerate(packed):
        lines.append(f"    // '{digit}'")
        for offset in range(0, len(data), stride):
            row = data[offset : offset + stride]
            lines.append("    " + " ".join(f"0x{byte:02x}," for byte in row))
    lines.append("};")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--height", type=int, default=160, help="glyph height in pixels")
    parser.add_argument("--width", type=int, default=0, help="minimum cell width in pixels")
    args = parser.parse_args()

    if not FONT_PATH.is_file():
        sys.stderr.write(f"font not found: {FONT_PATH}\n")
        return 1

    packed, widths, height = build(args.height, args.width)
    OUTPUT_PATH.write_text(emit(packed, widths, height), encoding="utf-8", newline="\n")
    total = sum(len(data) for data in packed)
    print(f"wrote {OUTPUT_PATH.relative_to(REPO_ROOT)} ({height}px tall, {total} bytes)")
    print(f"digit cell widths: {widths}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
